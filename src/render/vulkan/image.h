#ifndef BLUE_RENDER_VULKAN_IMAGE_H_
#define BLUE_RENDER_VULKAN_IMAGE_H_

#include <vk_mem_alloc.h>
#include <vulkan/vulkan.h>

#include <cstddef>
#include <cstdint>
#include <span>
#include <vector>

#include "render/vulkan/vulkan_context.h"

namespace blue::render::vulkan {

struct ImageDesc {
  VkExtent2D extent{};
  VkFormat format = VK_FORMAT_UNDEFINED;
  VkImageUsageFlags usage = 0;
  VkImageAspectFlags aspect = VK_IMAGE_ASPECT_COLOR_BIT;
  // More than one layer makes an array image; a cube has 6 per cube.
  uint32_t array_layers = 1;
  // 1 = no mips; MipLevelCount(extent) for a full chain.
  uint32_t mip_levels = 1;
  // Cube-compatible: array_layers must be 6 and the extent square; view()
  // is then a cube view.
  bool cube = false;
  // Gives the image its own memory block. Worth it for large render targets
  // that are recreated on resize; small textures share blocks.
  bool dedicated = false;
};

// Returns the mip count of a full chain down to 1 x 1 for `extent`.
[[nodiscard]] uint32_t MipLevelCount(VkExtent2D extent);

// Returns the size of one texel of `format` in bytes, or 0 for formats the
// upload path does not handle (block-compressed, depth, packed).
[[nodiscard]] uint32_t TexelSize(VkFormat format);

// Which part of an image a view covers. A zero count means "all remaining".
struct ImageViewDesc {
  VkImageViewType type = VK_IMAGE_VIEW_TYPE_2D;
  uint32_t base_mip = 0;
  uint32_t mip_count = 1;
  uint32_t base_layer = 0;
  uint32_t layer_count = 1;
};

// An image view owned on its own, e.g. one mip of one cube face as a render
// target. Must not outlive the image it views. Move-only; a moved-from view
// is empty. Not thread-safe.
class ImageView {
 public:
  ImageView() = default;
  ImageView(VkDevice device, VkImageView view) : device_(device), view_(view) {}
  ~ImageView();

  ImageView(const ImageView&) = delete;
  ImageView& operator=(const ImageView&) = delete;
  ImageView(ImageView&& other) noexcept;
  ImageView& operator=(ImageView&& other) noexcept;

  [[nodiscard]] VkImageView handle() const { return view_; }

 private:
  void Release();

  VkDevice device_ = VK_NULL_HANDLE;
  VkImageView view_ = VK_NULL_HANDLE;
};

// Device-local 2D image (single, array or cube) with a view of all its mips
// and layers, backed by a VMA allocation. An array image (not a cube) also
// has one 2D view per layer of mip 0. Layouts are not tracked: whoever
// records commands on the image knows its layout. Move-only; a moved-from
// image is empty. Not thread-safe.
class Image {
 public:
  Image() = default;
  Image(const VulkanContext& context, const ImageDesc& desc);
  ~Image();

  Image(const Image&) = delete;
  Image& operator=(const Image&) = delete;
  Image(Image&& other) noexcept;
  Image& operator=(Image&& other) noexcept;

  [[nodiscard]] VkImage handle() const { return image_; }
  // Returns the view of every mip and layer: 2D for a single layer, 2D array
  // for an array image, cube for a cube image.
  [[nodiscard]] VkImageView view() const { return view_; }
  // Returns the 2D view of `layer` (mip 0), which must be less than
  // array_layers() of an array image. Only array images have these views; a
  // single-layer or cube image returns view().
  [[nodiscard]] VkImageView layer_view(uint32_t layer) const {
    return layer_views_.empty() ? view_ : layer_views_[layer];
  }
  // Creates an additional view of this image; it must be destroyed before
  // the image.
  [[nodiscard]] ImageView CreateView(const ImageViewDesc& desc) const;

  [[nodiscard]] VkFormat format() const { return format_; }
  [[nodiscard]] VkExtent2D extent() const { return extent_; }
  [[nodiscard]] VkImageAspectFlags aspect() const { return aspect_; }
  [[nodiscard]] uint32_t array_layers() const { return array_layers_; }
  [[nodiscard]] uint32_t mip_levels() const { return mip_levels_; }
  // Device memory used by the image, in bytes.
  [[nodiscard]] VkDeviceSize size_bytes() const { return size_bytes_; }

 private:
  // Returns a new view the caller owns.
  [[nodiscard]] VkImageView CreateRawView(const ImageViewDesc& desc) const;
  void Release();

  VkDevice device_ = VK_NULL_HANDLE;
  VmaAllocator allocator_ = VK_NULL_HANDLE;
  VkImage image_ = VK_NULL_HANDLE;
  VkImageView view_ = VK_NULL_HANDLE;
  std::vector<VkImageView> layer_views_;
  VmaAllocation allocation_ = VK_NULL_HANDLE;
  VkFormat format_ = VK_FORMAT_UNDEFINED;
  VkExtent2D extent_{};
  VkImageAspectFlags aspect_ = VK_IMAGE_ASPECT_COLOR_BIT;
  uint32_t array_layers_ = 1;
  uint32_t mip_levels_ = 1;
  VkDeviceSize size_bytes_ = 0;
};

// Creates a sampled color image from CPU texels and blocks until it is ready.
// `texels` holds mip 0 of every layer, tightly packed, layer after layer
// (TexelSize(desc.format) bytes per texel, rows top to bottom); its size must
// match exactly. When desc.mip_levels > 1 the other mips are generated by
// linear blits (nearest when the format cannot be filtered; with no blit
// support at all the image gets a single mip and a warning is logged). The
// usage flags the upload needs are added to desc.usage. Leaves every
// subresource in SHADER_READ_ONLY_OPTIMAL. A size mismatch is fatal.
[[nodiscard]] Image CreateSampledImage(const VulkanContext& context,
                                       ImageDesc desc,
                                       std::span<const std::byte> texels);

// One image of a CreateImagesFromMipChains() batch.
struct MipChainUpload {
  // A single-layer 2D image; mip_levels must equal mips.size().
  ImageDesc desc;
  // The bytes of each level, level 0 first, in the copy layout of
  // desc.format (tightly packed rows, or rows of 4 x 4 blocks for
  // block-compressed formats). Borrowed for the call.
  std::span<const std::span<const std::byte>> mips;
};

// Creates sampled images from ready mip chains, block-compressed formats
// included, with no blits: the levels stream through bounded staging memory
// (StagingUploader: submissions of at most 16 MiB each, never a staging
// buffer of the whole batch); blocks until the copies finished. Level
// sizes are the caller's contract (see TextureCache::Upload(), which
// validates them). The usage flags the upload needs are added. Leaves every
// image in SHADER_READ_ONLY_OPTIMAL. Returns the images in the order of
// `uploads`.
[[nodiscard]] std::vector<Image> CreateImagesFromMipChains(
    const VulkanContext& context, std::span<const MipChainUpload> uploads);

}  // namespace blue::render::vulkan

#endif  // BLUE_RENDER_VULKAN_IMAGE_H_
