//! Builds the native libraries (`blue_sim_c`, `netcode`) with CMake and tells
//! rustc how to link them.
//!
//! CMake runs through `std::process::Command` rather than the `cmake` crate:
//! the invocation is three fixed commands, the `cmake` crate would add a
//! dependency (and its own `cc` dependency) for no gain, and it insists on
//! choosing the build directory layout and install step, while we only need
//! two targets and the link manifest CMake writes next to them.
//!
//! Environment:
//! - `BLUE_NATIVE_PREBUILT=<dir>`: skip CMake and link from an existing
//!   `BLUE_SIM_ONLY=ON` build directory (Docker builds, fast local iteration).
//! - `BLUE_NATIVE_JOBS=<n>`: parallel build jobs (default: available cores).
//!
//! The link manifest (`<build>/blue_sim_c.link`, one archive per line in link
//! order, and `<build>/blue_sim_c.syslibs`) is generated by the repository's
//! CMake (`blue_write_link_manifest`), so it follows the target graph.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

const MANIFEST: &str = "blue_sim_c.link";
const SYSLIBS: &str = "blue_sim_c.syslibs";

fn main() {
    if let Err(message) = run() {
        // A build script reports failure by exiting non-zero; the message is
        // shown by cargo.
        eprintln!("blue-native build failed: {message}");
        std::process::exit(1);
    }
}

fn run() -> Result<(), String> {
    println!("cargo::rerun-if-env-changed=BLUE_NATIVE_PREBUILT");
    println!("cargo::rerun-if-env-changed=BLUE_NATIVE_JOBS");
    println!("cargo::rerun-if-changed=build.rs");

    let build_dir = match env::var_os("BLUE_NATIVE_PREBUILT") {
        Some(dir) if !dir.is_empty() => {
            let dir = PathBuf::from(dir);
            // Relink when the prebuilt tree is rebuilt.
            println!("cargo::rerun-if-changed={}", dir.join(MANIFEST).display());
            dir
        }
        _ => build_with_cmake()?,
    };
    emit_link_lines(&build_dir)
}

fn repo_root() -> Result<PathBuf, String> {
    let manifest_dir = env::var_os("CARGO_MANIFEST_DIR").ok_or("CARGO_MANIFEST_DIR unset")?;
    // server/crates/blue-native -> repository root.
    let root = PathBuf::from(manifest_dir).join("../../..");
    let root = root
        .canonicalize()
        .map_err(|e| format!("cannot resolve repository root {}: {e}", root.display()))?;
    if !root.join("CMakeLists.txt").is_file() {
        return Err(format!("{} has no CMakeLists.txt", root.display()));
    }
    Ok(root)
}

fn build_with_cmake() -> Result<PathBuf, String> {
    let root = repo_root()?;
    // Only native sources and CMake files trigger a rebuild; Rust edits do not.
    for path in ["CMakeLists.txt", "cmake", "src", "CMakePresets.json"] {
        println!("cargo::rerun-if-changed={}", root.join(path).display());
    }
    let out_dir = PathBuf::from(env::var_os("OUT_DIR").ok_or("OUT_DIR unset")?);
    let build_dir = out_dir.join("cmake-build");
    let jobs = env::var("BLUE_NATIVE_JOBS").ok().unwrap_or_else(|| {
        std::thread::available_parallelism()
            .map(|n| n.get().to_string())
            .unwrap_or_else(|_| "4".to_owned())
    });

    let mut configure = Command::new("cmake");
    configure
        .arg("-S")
        .arg(&root)
        .arg("-B")
        .arg(&build_dir)
        .arg("-DBLUE_SIM_ONLY=ON")
        .arg("-DBLUE_BUILD_TESTS=OFF")
        .arg("-DCMAKE_BUILD_TYPE=RelWithDebInfo");
    run_command(&mut configure, "cmake configure")?;

    let mut build = Command::new("cmake");
    build
        .arg("--build")
        .arg(&build_dir)
        .arg("--target")
        .arg("blue_sim_c")
        .arg("netcode")
        .arg("--parallel")
        .arg(&jobs);
    run_command(&mut build, "cmake build")?;
    Ok(build_dir)
}

fn run_command(command: &mut Command, what: &str) -> Result<(), String> {
    let status = command
        .status()
        .map_err(|e| format!("{what}: cannot start cmake ({e}); is it installed?"))?;
    if status.success() {
        Ok(())
    } else {
        Err(format!("{what} failed with {status}"))
    }
}

fn read_lines(path: &Path) -> Result<Vec<String>, String> {
    let text = fs::read_to_string(path).map_err(|e| {
        format!(
            "cannot read {} ({e}); is this a BLUE_SIM_ONLY=ON build directory?",
            path.display()
        )
    })?;
    Ok(text
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty())
        .map(str::to_owned)
        .collect())
}

fn emit_link_lines(build_dir: &Path) -> Result<(), String> {
    let archives = read_lines(&build_dir.join(MANIFEST))?;
    let syslibs = read_lines(&build_dir.join(SYSLIBS))?;
    let mut seen_names: Vec<String> = Vec::new();
    for archive in &archives {
        let path = Path::new(archive);
        if !path.is_file() {
            return Err(format!(
                "archive {archive} listed in the manifest is missing"
            ));
        }
        let dir = path.parent().ok_or("archive without a directory")?;
        let file = path
            .file_name()
            .and_then(|f| f.to_str())
            .ok_or("archive name is not UTF-8")?;
        // `+verbatim` passes the file name as is (`-l:libfoo.a`), so two
        // archives with the same name in different directories would clash.
        if seen_names.iter().any(|n| n == file) {
            return Err(format!("two archives named {file} in the manifest"));
        }
        seen_names.push(file.to_owned());
        println!("cargo::rerun-if-changed={archive}");
        println!("cargo::rustc-link-search=native={}", dir.display());
        // Manifest order is a valid static link order; rustc keeps the order
        // of these lines on the final link line.
        println!("cargo::rustc-link-lib=static:-bundle,+verbatim={file}");
    }
    for lib in &syslibs {
        println!("cargo::rustc-link-lib=dylib={lib}");
    }
    println!("cargo::metadata=build_dir={}", build_dir.display());
    Ok(())
}
